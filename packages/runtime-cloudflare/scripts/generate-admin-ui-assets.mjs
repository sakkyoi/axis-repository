import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, extname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const distRoot = resolve(packageRoot, "../admin-ui/dist");
const outputFile = resolve(packageRoot, "src/admin-ui-assets/generated.ts");

const contentTypes = new Map([
  [".css", "text/css; charset=utf-8"],
  [".html", "text/html; charset=utf-8"],
  [".js", "application/javascript; charset=utf-8"],
  [".json", "application/json; charset=utf-8"],
  [".map", "application/json; charset=utf-8"],
  [".svg", "image/svg+xml"],
  [".txt", "text/plain; charset=utf-8"],
  [".webmanifest", "application/manifest+json; charset=utf-8"],
  [".woff", "font/woff"],
  [".woff2", "font/woff2"],
]);

async function walk(directory) {
  const entries = await readdir(directory);
  const files = [];
  for (const entry of entries) {
    const path = resolve(directory, entry);
    const entryStat = await stat(path);
    if (entryStat.isDirectory()) {
      files.push(...await walk(path));
      continue;
    }
    if (entryStat.isFile() && extname(path) !== ".map") {
      files.push(path);
    }
  }
  return files;
}

function routePath(filePath) {
  const relativePath = relative(distRoot, filePath).split(sep).join("/");
  return `/${relativePath}`;
}

// The admin UI package builds the SPA and the plugin-ui library into the same
// dist directory, so restrict the worker asset map to what the SPA actually
// serves. Without this the worker ships plugin-ui.js and plugin-ui.d.ts and
// serves them at public URLs.
function isAdminUiAsset(path) {
  return path === "/index.html" || path.startsWith("/assets/");
}

function contentType(filePath) {
  return contentTypes.get(extname(filePath)) ?? "application/octet-stream";
}

async function main() {
  const files = (await walk(distRoot)).sort();
  const entries = [];

  for (const file of files) {
    const path = routePath(file);
    if (!isAdminUiAsset(path)) {
      continue;
    }
    const bodyBase64 = (await readFile(file)).toString("base64");
    const asset = { contentType: contentType(file), bodyBase64 };
    entries.push([path, asset]);
    if (path === "/index.html") {
      entries.push(["/", asset]);
    }
  }

  if (!entries.some(([path]) => path === "/index.html")) {
    throw new Error(`No admin UI index.html found under ${distRoot}; run the admin UI build first`);
  }

  entries.sort(([left], [right]) => left.localeCompare(right));

  const source = [
    "// This file is generated by scripts/generate-admin-ui-assets.mjs.",
    "// Run `pnpm --filter @axis-repository/runtime-cloudflare build` after changing admin-ui assets.",
    "export const adminUiAssetEntries = [",
    ...entries.map(([path, asset]) => `  [${JSON.stringify(path)}, ${JSON.stringify(asset)}],`),
    "] as const;",
    "",
  ].join("\n");

  await writeFile(outputFile, source);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
