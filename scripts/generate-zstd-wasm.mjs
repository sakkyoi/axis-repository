import { createRequire } from "node:module";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

/**
 * Vendors the zstd WebAssembly binary and its symbol map.
 *
 * `@bokuweb/zstd-wasm` ships libzstd built for the web, but its packaging does
 * not survive a Cloudflare Worker: the loader resolves its `.wasm` with
 * `fetch(new URL(...))`, module scope has no I/O, and the package exports map
 * offers only a root entry that resolves to a `fs`-reading build under Node.
 * Rather than fight that with per-runtime aliases, the binary is vendored and
 * driven directly — the compression is still libzstd, only the few lines of
 * glue around it are ours.
 *
 * The binary is copied rather than embedded because a Worker refuses to
 * compile WebAssembly at run time ("Wasm code generation disallowed by
 * embedder"); it has to be imported so the platform compiles it at deploy.
 *
 * The binary exports minified names, so the map is read out of the shipped
 * glue rather than hard-coded; a version bump that renames them is picked up
 * by regenerating instead of failing at run time.
 *
 * Regenerate with: node scripts/generate-zstd-wasm.mjs
 */

// Resolve from the plugin that depends on it: pnpm keeps the package under
// plugins/apt/node_modules rather than the workspace root.
const require = createRequire(new URL("../plugins/apt/package.json", import.meta.url));
const packageRoot = new URL("./", pathToFileURL(require.resolve("@bokuweb/zstd-wasm")));
const sourceWasm = fileURLToPath(new URL("zstd.wasm", packageRoot));
const glue = readFileSync(fileURLToPath(new URL("zstd.js", packageRoot)), "utf8");
const version = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../package.json", packageRoot)), "utf8"),
).version;

const wasmPath = fileURLToPath(new URL("../plugins/apt/shared/zstd.wasm", import.meta.url));
const symbolsPath = fileURLToPath(new URL("../plugins/apt/shared/zstd-symbols.generated.ts", import.meta.url));

/** Reads `var _NAME = (... wasmExports['x'])` out of the shipped glue. */
function exportSymbol(name) {
  const found = new RegExp(`\\b_${name} = .*?wasmExports\\['(\\w+)'\\]`).exec(glue);
  if (!found?.[1]) {
    throw new Error(`Could not find the wasm export backing ${name}`);
  }
  return found[1];
}

function importSymbol(name) {
  const table = /var wasmImports = \{([\s\S]*?)\};/.exec(glue)?.[1];
  const found = table && new RegExp(`(\\w+): ${name},`).exec(table);
  if (!found?.[1]) {
    throw new Error(`Could not find the wasm import slot for ${name}`);
  }
  return found[1];
}

const wasmExports = {
  memory: /wasmMemory = wasmExports\['(\w+)'\]/.exec(glue)?.[1],
  callConstructors: /___wasm_call_ctors = wasmExports\['(\w+)'\]/.exec(glue)?.[1],
  isError: exportSymbol("ZSTD_isError"),
  compressBound: exportSymbol("ZSTD_compressBound"),
  compress: exportSymbol("ZSTD_compress"),
  malloc: exportSymbol("malloc"),
  free: exportSymbol("free"),
};
const wasmImports = {
  procExit: importSymbol("_proc_exit"),
  keepaliveClear: importSymbol("__emscripten_runtime_keepalive_clear"),
  abort: importSymbol("__abort_js"),
  setItimer: importSymbol("__setitimer_js"),
  resizeHeap: importSymbol("_emscripten_resize_heap"),
};

for (const [name, symbol] of [...Object.entries(wasmExports), ...Object.entries(wasmImports)]) {
  if (!symbol) {
    throw new Error(`Could not resolve the wasm symbol for ${name}`);
  }
}

copyFileSync(sourceWasm, wasmPath);
writeFileSync(symbolsPath, `// Generated by scripts/generate-zstd-wasm.mjs — do not edit.
// Source: @bokuweb/zstd-wasm ${version} (libzstd compiled to WebAssembly)

/** Names the binary exports its functions under, read from the shipped glue. */
export const ZSTD_WASM_EXPORTS = ${JSON.stringify(wasmExports, null, 2)} as const;

/** Slots the binary expects its host functions in. */
export const ZSTD_WASM_IMPORTS = ${JSON.stringify(wasmImports, null, 2)} as const;
`);

console.log(`wrote ${wasmPath} (${readFileSync(sourceWasm).byteLength} bytes)`);
console.log(`wrote ${symbolsPath}`);
console.log(`  exports ${JSON.stringify(wasmExports)}`);
console.log(`  imports ${JSON.stringify(wasmImports)}`);
